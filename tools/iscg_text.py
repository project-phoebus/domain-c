HARD_WORK = '''{ hard_work - rule which_transform applied to solution (the node il under
  inh): unless its result kind must be permissible and is not, or its
  subject's children hold more registers that may deadlock the
  scheduler than it allows, its pass-1 action makes the new solution
  (marked could-deadlock when it holds a physical register that is
  modifiable, not serialized and floating or not a well-known one); a
  proper_subtree is kept once per call of pattern_matcher; any other
  is compared with each solution of the parent of its kind (dropped when
  similar to one or dominated by one; one it dominates is removed) and
  appended there when its kind is permissible; the work list gets the
  action's work solution when the result was appended, or was kept but
  not permissible and is not a dead end.

  0x20042C, 0x5E4 bytes: solution 8, work_list 12, solutions_of_parent
  16, il 20, inh 24, permissible_solution_kinds 28, which_transform 32
  (a longword); D6 add_this_to_parent (the action's result, through
  -40), -36 add_this_to_work_list, D3 the solution is wanted, D4 it was
  appended (and the loop's count).  The count of could-deadlock
  children is unrolled: the subject itself when it has none, then
  children 1..5 each while it has that many (`cmpi.b #k,(114,A2);
  bcs').  The flags are bytes by rule (`tst.b (2255,A0)' of A5 + rule;
  `tst.b (2823,A0)').  Neither appended nor wanted is set when the
  action gives no result: the work list's test reads them as they are
  (`tst.b D4' at 0x200966), as the image does.  The `not appended' trace
  of an unpermitted kind ends in the same writeln as a solution not
  wanted (Rev 8.89 shares the call).

  Not known from the original: the locals' names but add_this_to_parent
  and permissible_solution_kinds (the traces print them). }

procedure hard_work(
    solution: isc_solution_ptr_t;
    work_list: solution_list_ptr_t;
    solutions_of_parent: solution_list_ptr_t;
    il: univ_ptr;
    inh: inherited_attributes_ptr_t;
    permissible_solution_kinds: solution$set_t;
    which_transform: integer32); options(val_param, internal);
label
  done;
var
  add_this_to_parent: isc_solution_ptr_t;
  add_this_to_work_list: isc_solution_ptr_t;
  n: integer32;
  ok: boolean;
  wanted: boolean;
  appended: boolean;
  i: integer32;
  p: solution_cell_ptr_t;
  other: isc_solution_ptr_t;
begin
  if isc_user_routines_354 then begin
    write('Pattern ');
    write(which_transform:1);
    write(' matched the syntax.');
    writeln;
  end;
  add_this_to_parent := nil;
  add_this_to_work_list := nil;
  if pm_check_permissible[which_transform] and
     not (solution$t(isc_tool_generated_readonly_tables.result_kind[which_transform])
          in permissible_solution_kinds) then begin
    if isc_user_routines_356 or isc_user_routines_354 then begin
      write('Dead end.');
      writeln;
    end;
  end
  else begin
    n := 0;
    if solution^.f114.nchildren = 0 then begin
      if solution^.f114.b6 then
        n := 1;
    end;
    if solution^.f114.nchildren >= 1 then begin
      if solution^.children[1]^.f114.b6 then
        n := n + 1;
    end;
    if solution^.f114.nchildren >= 2 then begin
      if solution^.children[2]^.f114.b6 then
        n := n + 1;
    end;
    if solution^.f114.nchildren >= 3 then begin
      if solution^.children[3]^.f114.b6 then
        n := n + 1;
    end;
    if solution^.f114.nchildren >= 4 then begin
      if solution^.children[4]^.f114.b6 then
        n := n + 1;
    end;
    if solution^.f114.nchildren >= 5 then begin
      if solution^.children[5]^.f114.b6 then
        n := n + 1;
    end;
    if pm_no_could_deadlock_child[which_transform] then
      ok := n = 0
    else
      ok := n <= 1;
    if ok then begin
      pm_pass_1_action[which_transform]^(solution^, il, inh, add_this_to_work_list,
                                         add_this_to_parent);
      if add_this_to_parent <> nil then begin
        if add_this_to_parent^.eval_order <> 0 then begin
          if add_this_to_parent^.f76.physical and
             not add_this_to_parent^.f76.no_modify and
             not add_this_to_parent^.f76.serialize then begin
            if (solution$t(add_this_to_parent^.kind) in
                [solution$fp_reg_pair_high, solution$fp_reg_pair_low, solution$fp_reg,
                 solution$fp_reg_pair, solution$fp_reg_quad]) or
               ((add_this_to_parent^.f76.reg <>
                 isc_solution_ptr_t(isc_user_routines_330)^.f76.reg) and
                (add_this_to_parent^.f76.reg <>
                 isc_solution_ptr_t(isc_user_routines_31c)^.f76.reg)) then
              add_this_to_parent^.f114.b6 := true;
          end;
        end
        else begin
          add_this_to_parent := nil;
          add_this_to_work_list := nil;
        end;
      end;
    end
    else if isc_user_routines_356 or isc_user_routines_354 then begin
      write('Invalid use of physical registers.');
      writeln;
    end;
  end;
  if add_this_to_parent <> nil then begin
    wanted := true;
    if add_this_to_parent^.kind = ord(solution$proper_subtree) then begin
      if pm_proper_subtree_seen then
        wanted := false;
      pm_proper_subtree_seen := true;
    end
    else begin
      if isc_user_routines_354 then begin
        write('Comparing the following solution to all previous solutions_of_parent:');
        writeln;
        dump_solution(add_this_to_parent, 0, false);
      end;
      i := 0;
      p := solutions_of_parent^.first;
      while p <> nil do begin
        other := p^.sol;
        i := i + 1;
        if add_this_to_parent^.kind = other^.kind then begin
          if isc_user_routines_354 then begin
            write('Solution ');
            write(i:1);
            write(' is of the same kind.');
            writeln;
          end;
          if similar_solutions(add_this_to_parent, other) then begin
            if isc_user_routines_354 then begin
              write('This solution is similar. We do not want the new solution. Go to done.');
              writeln;
            end;
            wanted := false;
            goto done;
          end;
          if clearly_dominates(add_this_to_parent, other) then begin
            if isc_user_routines_354 then begin
              write('The new solution clearly dominates this solution. This solution was removed from the solutions_of_parent. We want the new solution.');
              writeln;
            end;
            solution_list$delete(solutions_of_parent, other);
          end
          else if clearly_dominates(other, add_this_to_parent) then begin
            if isc_user_routines_354 then begin
              write('This solution clearly dominates the new solution. We do not want the new solution. Go to done.');
              writeln;
            end;
            wanted := false;
            goto done;
          end
          else if isc_user_routines_354 then begin
            write('Neither solution dominates. We want the new solution.');
            writeln;
          end;
        end
        else if isc_user_routines_354 then begin
          write('Solution ');
          write(i:1);
          write(' is not of the same kind.');
          writeln;
        end;
        p := p^.next;
      end;
    end;
done:
    appended := false;
    if wanted then begin
      if (add_this_to_parent^.kind = ord(solution$proper_subtree)) or
         (solution$t(add_this_to_parent^.kind) in permissible_solution_kinds) then begin
        appended := true;
        if isc_user_routines_354 then begin
          write('That solution was appended to the solutions_of_parent.');
          writeln;
        end;
        solution_list$append(solutions_of_parent, add_this_to_parent);
      end
      else if isc_user_routines_354 then begin
        write('add_this_to_parent^.kind is NOT in permissible_solution_kinds.');
        writeln;
        write('We wanted the new solution, but ...');
        writeln;
        write('That solution was NOT appended to the solutions_of_parent.');
        writeln;
      end;
    end
    else if isc_user_routines_354 then begin
      write('That solution was NOT appended to the solutions_of_parent.');
      writeln;
    end;
  end;
  if add_this_to_work_list <> nil then begin
    if appended or
       (not (solution$t(add_this_to_parent^.kind) in permissible_solution_kinds) and wanted and
        not pm_sol_flags_ptr_t(add_this_to_parent)^.f81.dead_end) then begin
      if isc_user_routines_354 then begin
        write('Adding the following solution to the work list:');
        writeln;
        dump_solution(add_this_to_work_list, 0, false);
      end;
      solution_list$append(work_list, add_this_to_work_list);
    end
    else if isc_user_routines_354 then begin
      write('The following solution was NOT added to the work list:');
      writeln;
      dump_solution(add_this_to_work_list, 0, false);
    end;
  end;
end;'''

