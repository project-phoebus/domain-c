PASS_2 = '''{ pass_2 - pass 2 over sol (heading in isc.pvt.pas): nothing for nil or
  a solution already through pass 2; a solution a rule made passes its
  subject (before_transform, +88: the proper_subtree it came from takes
  its evaluation order) to pass 2 first, any other its children in its
  evaluation order (1 left to right, 2 right to left, anything else
  printed as an error); then the pass-2 attributes are reset (base and
  index register to isc_user_routines_31c, false_label, object_with_name,
  live_range and live_range_of_imaginary_part cleared,
  already_through_pass_2 cleared) and, for a solution a rule made, the
  rule's pass-2 action is called; the solution is then through pass 2.

  0x18C588, 0x218 bytes: sol 8, depth 12 (a word); A2 sol, D2 depth.
  The action's arguments are pushed from -4 (sol), A3 (sol), -8
  (before_transform) and A2 (sol): (sol^, before_transform, sol^, sol).
  The six calls of the children and the subject's share one call
  (`bra 0x18C6E2').

  Not known from the original: the locals. }

procedure pass_2;
begin
  isc_user_routines_2fc := isc_user_routines_2fc + 1;
  if sol <> nil then
    if not sol^.f114.pass_2_done then begin
      if sol^.chain <> nil then begin
        if sol^.chain^.kind = ord(solution$proper_subtree) then
          sol^.chain^.eval_order := sol^.eval_order;
        pass_2(sol^.chain, depth + 1);
      end
      else if sol^.f114.nchildren <> 0 then begin
        if sol^.eval_order = 1 then begin
          if sol^.children[1] <> nil then
            pass_2(sol^.children[1], depth + 1);
          if sol^.children[2] <> nil then
            pass_2(sol^.children[2], depth + 1);
          if sol^.children[3] <> nil then
            pass_2(sol^.children[3], depth + 1);
          if sol^.children[4] <> nil then
            pass_2(sol^.children[4], depth + 1);
          if sol^.children[5] <> nil then
            pass_2(sol^.children[5], depth + 1);
        end
        else if sol^.eval_order = 2 then begin
          if sol^.children[5] <> nil then
            pass_2(sol^.children[5], depth + 1);
          if sol^.children[4] <> nil then
            pass_2(sol^.children[4], depth + 1);
          if sol^.children[3] <> nil then
            pass_2(sol^.children[3], depth + 1);
          if sol^.children[2] <> nil then
            pass_2(sol^.children[2], depth + 1);
          if sol^.children[1] <> nil then
            pass_2(sol^.children[1], depth + 1);
        end
        else begin
          write('ERROR: unknown evaluation order (');
          write(sol^.eval_order);
          write(').');
          writeln;
        end;
      end;
      sol^.base_reg := lr_ptr_t(isc_user_routines_31c);
      sol^.index_reg := lr_ptr_t(isc_user_routines_31c);
      sol^.l16 := 0;
      sol^.obj_w_name := nil;
      sol^.live_range := nil;
      sol^.lr2 := nil;
      sol^.f114.pass_2_done := false;
      if sol^.chain <> nil then
        p2_pass_2_action[sol^.rule]^(sol^, sol^.chain, sol^, sol);
      sol^.f114.pass_2_done := true;
    end;
end;'''

